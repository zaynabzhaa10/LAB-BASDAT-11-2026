
-- 1. Membuat tabel anggota
CREATE TABLE anggota (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_anggota VARCHAR(50) NOT NULL,
    kota_domisili VARCHAR(20) NOT NULL
);

-- 2. Membuat tabel buku
CREATE TABLE buku (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    judul_buku VARCHAR(100) NOT NULL,
    genre VARCHAR(20) NOT NULL,
    stok INTEGER DEFAULT 1
);

-- 3. Membuat tabel peminjaman
CREATE TABLE peminjaman (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_anggota INTEGER REFERENCES anggota(id),
    id_buku INTEGER REFERENCES buku(id),
    tanggal_pinjam DATE NOT NULL,
    tanggal_kembali DATE DEFAULT NULL,
    denda INTEGER DEFAULT 0
);

-- 4. Membuat index genre buku
CREATE INDEX idx_buku_genre
ON buku(genre);

-- 5. Membuat index kota domisili anggota
CREATE INDEX idx_anggota_kota_domisili
ON anggota(kota_domisili);


SELECT table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN ('anggota', 'buku', 'peminjaman')
ORDER BY table_name;

SELECT tablename, indexname
FROM pg_indexes
WHERE schemaname = 'public'
  AND tablename IN ('anggota', 'buku', 'peminjaman')
ORDER BY tablename, indexname;


SELECT tablename, indexname
FROM pg_indexes
WHERE schemaname = 'public'
  AND indexname IN (
      'idx_buku_genre',
      'idx_anggota_kota_domisili'
  )
ORDER BY indexname;
